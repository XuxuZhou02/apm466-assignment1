"""Fixed-rate bullet bond: coupon schedule, accrued interest and cash flows."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date

import numpy as np
from dateutil.relativedelta import relativedelta

DAYS_PER_YEAR = 365.0  # Canadian money-market / GoC bond convention (ACT/365)


def year_fraction(start: date, end: date) -> float:
    """ACT/365 year fraction between two dates."""
    return (end - start).days / DAYS_PER_YEAR


@dataclass(frozen=True)
class Bond:
    """A fixed-coupon government bond paying ``freq`` coupons per year."""

    isin: str
    name: str
    coupon: float  # annual coupon rate, e.g. 0.0275 for 2.75%
    maturity: date
    freq: int = 2
    face: float = 100.0

    @property
    def coupon_amount(self) -> float:
        """Cash coupon paid on each coupon date per ``face`` of notional."""
        return self.coupon * self.face / self.freq

    def coupon_dates(self, settle: date) -> list[date]:
        """All coupon dates strictly after ``settle``, in ascending order.

        Dates are generated by stepping back from maturity in whole
        coupon periods, which avoids day-of-month drift.
        """
        months = 12 // self.freq
        dates = []
        k = 0
        while True:
            d = self.maturity - relativedelta(months=months * k)
            if d <= settle:
                break
            dates.append(d)
            k += 1
        return dates[::-1]

    def previous_coupon_date(self, settle: date) -> date:
        """Last coupon date on or before ``settle``."""
        months = 12 // self.freq
        first_future = self.coupon_dates(settle)[0]
        return first_future - relativedelta(months=months)

    def accrued_interest(self, settle: date) -> float:
        """Accrued interest using the ACT/365 convention for GoC bonds."""
        days = (settle - self.previous_coupon_date(settle)).days
        return self.coupon * self.face * days / DAYS_PER_YEAR

    def dirty_price(self, clean_price: float, settle: date) -> float:
        """Invoice (dirty) price = quoted clean price + accrued interest."""
        return clean_price + self.accrued_interest(settle)

    def cash_flows(self, settle: date) -> tuple[np.ndarray, np.ndarray]:
        """Remaining cash flows as ``(times_in_years, amounts)``."""
        dates = self.coupon_dates(settle)
        times = np.array([year_fraction(settle, d) for d in dates])
        amounts = np.full(len(dates), self.coupon_amount)
        amounts[-1] += self.face
        return times, amounts

    def time_to_maturity(self, settle: date) -> float:
        return year_fraction(settle, self.maturity)
